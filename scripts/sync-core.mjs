#!/usr/bin/env node
// Copies packages/core/src into supabase/functions/_shared/core so Edge Functions can import it.
// `--check` exits non-zero if the copy is stale (used in CI).
import { readdirSync, readFileSync, writeFileSync, mkdirSync, rmSync, existsSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const src = join(root, 'packages/core/src');
const dest = join(root, 'supabase/functions/_shared/core');
const header = '// GENERATED by scripts/sync-core.mjs from packages/core/src. Do not edit.\n';
const check = process.argv.includes('--check');

const files = readdirSync(src).filter((f) => f.endsWith('.ts'));
let stale = false;
if (!check) {
  rmSync(dest, { recursive: true, force: true });
  mkdirSync(dest, { recursive: true });
}
for (const f of files) {
  const content = header + readFileSync(join(src, f), 'utf8');
  const target = join(dest, f);
  if (check) {
    if (!existsSync(target) || readFileSync(target, 'utf8') !== content) {
      console.error(`stale: ${target}`);
      stale = true;
    }
  } else writeFileSync(target, content);
}
if (check) {
  const extra = existsSync(dest) ? readdirSync(dest).filter((f) => !files.includes(f)) : [];
  for (const f of extra) console.error(`extra: ${join(dest, f)}`);
  if (stale || extra.length) {
    console.error('Run `npm run sync-core` and commit the result.');
    process.exit(1);
  }
  console.log('core copy is up to date');
} else console.log(`synced ${files.length} files to ${dest}`);
